import org.jetbrains.compose.desktop.application.dsl.TargetFormat

plugins {
    alias(libs.plugins.kotlin.jvm)
    alias(libs.plugins.compose.multiplatform)
    alias(libs.plugins.compose.compiler)
    alias(libs.plugins.kotlin.serialization)
}

kotlin { jvmToolchain(21) }

// The release version comes from the tag: ./gradlew ... -PappVersion=0.3.0
val appVersion = (findProperty("appVersion") as String?) ?: "0.3.0-dev"
val buildInfoDir = layout.buildDirectory.dir("generated/buildinfo")
val generateBuildInfo by tasks.registering {
    inputs.property("version", appVersion)
    outputs.dir(buildInfoDir)
    doLast {
        val f = buildInfoDir.get().file("dev/silage/app/BuildInfo.kt").asFile
        f.parentFile.mkdirs()
        f.writeText(
            "package dev.silage.app\n\n" +
                "/** Generated by the build (see app/build.gradle.kts). */\n" +
                "object BuildInfo {\n    const val NAME = \"Silage\"\n    const val VERSION = \"$appVersion\"\n}\n",
        )
    }
}
sourceSets.main { kotlin.srcDir(generateBuildInfo) }

dependencies {
